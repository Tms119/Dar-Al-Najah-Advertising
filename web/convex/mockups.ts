export const list = query({
  args: {},
  handler: async (ctx) => {
    await requireAdmin(ctx);
    const rows = await ctx.db.query("mockups").order("desc").take(48);
    return await Promise.all(rows.map(async (m) => ({
      _id: m._id,
      _creationTime: m._creationTime,
      objectLabel: m.objectLabel,
      text: m.text,
      hadLogo: m.hadLogo,
      aspect: m.aspect,
      url: await ctx.storage.getUrl(m.storageId),
    })));
  },
});

export const remove = mutation({
  args: { id: v.id("mockups") },
  returns: v.null(),
  handler: async (ctx, { id }) => {
    await requireAdmin(ctx);
    const m = await ctx.db.get(id);
    if (!m) return null;
    await ctx.storage.delete(m.storageId);
    await ctx.db.delete(id);
    return null;
  },
});

/** Whether the image service keys are set (so the page can explain setup). */
export const status = query({
  args: {},
  returns: v.object({ connected: v.boolean() }),
  handler: async (ctx) => {
    await requireAdmin(ctx);
    return { connected: !!(env.CLOUDFLARE_ACCOUNT_ID && env.CLOUDFLARE_API_TOKEN) };
  },
});
